document.addEventListener('DOMContentLoaded', function() {
    const nameSelect = document.getElementById('name_select');
    const nameCustom = document.getElementById('name_custom');
    const codeSelect = document.getElementById('code_select');
    const codeCustom = document.getElementById('code_custom');
    
    // Check if editing existing language and set up initial state
    const existingName = nameCustom.value;
    const existingCode = codeCustom.value;
    
    if (existingName) {
        // Check if the existing name is in the predefined list
        let foundName = false;
        for (let option of nameSelect.options) {
            if (option.value === existingName) {
                nameSelect.value = existingName;
                foundName = true;
                break;
            }
        }
        
        // If not found, show custom input
        if (!foundName) {
            nameSelect.value = '__custom__';
            nameCustom.style.display = 'block';
        }
    }
    
    if (existingCode) {
        // Check if the existing code is in the predefined list
        let foundCode = false;
        for (let option of codeSelect.options) {
            if (option.value === existingCode) {
                codeSelect.value = existingCode;
                foundCode = true;
                break;
            }
        }
        
        // If not found, show custom input
        if (!foundCode) {
            codeSelect.value = '__custom__';
            codeCustom.style.display = 'block';
        }
    }
    
    // Handle name select change
    nameSelect.addEventListener('change', function() {
        const selectedValue = this.value;
        
        if (selectedValue === '__custom__') {
            // Show custom input for name
            nameCustom.style.display = 'block';
            nameCustom.required = true;
            nameCustom.focus();
        } else {
            // Hide custom input and use selected value
            nameCustom.style.display = 'none';
            nameCustom.required = false;
            nameCustom.value = selectedValue;
            
            // Auto-select corresponding code
            const selectedOption = this.options[this.selectedIndex];
            const languageCode = selectedOption.getAttribute('data-code');
            
            if (languageCode) {
                codeSelect.value = languageCode;
                codeCustom.style.display = 'none';
                codeCustom.required = false;
                codeCustom.value = languageCode;
            }
        }
    });
    
    // Handle code select change
    codeSelect.addEventListener('change', function() {
        const selectedValue = this.value;
        
        if (selectedValue === '__custom__') {
            // Show custom input for code
            codeCustom.style.display = 'block';
            codeCustom.required = true;
            codeCustom.focus();
        } else {
            // Hide custom input and use selected value
            codeCustom.style.display = 'none';
            codeCustom.required = false;
            codeCustom.value = selectedValue;
            
            // Auto-select corresponding name
            const selectedOption = this.options[this.selectedIndex];
            const languageName = selectedOption.getAttribute('data-name');
            
            if (languageName) {
                nameSelect.value = languageName;
                nameCustom.style.display = 'none';
                nameCustom.required = false;
                nameCustom.value = languageName;
            }
        }
    });
    
    // Sync custom inputs when typing
    nameCustom.addEventListener('input', function() {
        // If user is typing custom name, don't auto-sync to avoid interference
    });
    
    codeCustom.addEventListener('input', function() {
        // If user is typing custom code, don't auto-sync to avoid interference
    });
});
</script>
